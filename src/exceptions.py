"""Пользовательские исключения интернет-магазина."""


class ZeroQuantityError(ValueError):
    """Сообщить о попытке добавить товар с нулевым количеством."""

    def __init__(self) -> None:
        """Инициализировать исключение стандартным сообщением."""
        super().__init__("Товар с нулевым количеством не может быть добавлен.")
